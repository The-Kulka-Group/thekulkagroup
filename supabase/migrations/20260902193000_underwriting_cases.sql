-- Saved underwriting cases for LA-160. This migration stores the intake only.
-- Calculation inputs and results stay separate so a later engine can version
-- them without changing the case record.

create table underwriting_cases (
  id uuid primary key default gen_random_uuid(),
  case_number bigint generated by default as identity unique,
  name text not null check (btrim(name) <> ''),
  address text not null check (btrim(address) <> ''),
  development_type text not null default 'ground_up_multifamily'
    check (development_type = 'ground_up_multifamily'),
  status text not null default 'working'
    check (status in ('open', 'working', 'stuck', 'done')),
  proposed_units integer check (proposed_units > 0),
  average_unit_square_feet numeric check (average_unit_square_feet > 0),
  gross_building_square_feet numeric check (gross_building_square_feet > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table underwriting_case_assumptions (
  id uuid primary key default gen_random_uuid(),
  case_id uuid not null references underwriting_cases (id) on delete cascade,
  assumption_key text not null check (assumption_key in (
    'purchase_price',
    'monthly_rent',
    'hard_cost_per_gross_square_foot',
    'construction_months',
    'debt_percent',
    'interest_rate_percent',
    'exit_cap_rate_percent',
    'hold_years'
  )),
  value numeric not null check (value >= 0),
  unit text not null check (unit in (
    'usd',
    'usd_per_month',
    'usd_per_gross_square_foot',
    'months',
    'percent',
    'years'
  )),
  source_kind text not null default 'user_supplied'
    check (source_kind = 'user_supplied'),
  source_label text not null default 'User entered'
    check (btrim(source_label) <> ''),
  source_date date not null default current_date,
  review_state text not null default 'working'
    check (review_state in ('working', 'done')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (case_id, assumption_key),
  check (
    (assumption_key = 'purchase_price' and unit = 'usd')
    or (assumption_key = 'monthly_rent' and unit = 'usd_per_month')
    or (
      assumption_key = 'hard_cost_per_gross_square_foot'
      and unit = 'usd_per_gross_square_foot'
    )
    or (assumption_key = 'construction_months' and unit = 'months')
    or (
      assumption_key in ('debt_percent', 'interest_rate_percent', 'exit_cap_rate_percent')
      and unit = 'percent'
      and value <= 100
    )
    or (assumption_key = 'hold_years' and unit = 'years')
  )
);

create index underwriting_cases_updated_idx
  on underwriting_cases (updated_at desc, case_number desc);

create index underwriting_case_assumptions_case_idx
  on underwriting_case_assumptions (case_id, assumption_key);

-- Supabase exposes public tables through its API. Browser clients get no
-- policies, so only the server's direct Postgres connection can read or write.
alter table underwriting_cases enable row level security;
alter table underwriting_case_assumptions enable row level security;
